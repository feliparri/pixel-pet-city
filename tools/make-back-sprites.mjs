// Generates src/arcade/back-art.js from the board's own rear-view art, so the arcade's pets are the board's pixels in the board's palettes.
//   node tools/make-back-sprites.mjs [path-to-pixel-pet]      (default: ../pixel-pet next to this repo, or $PIXEL_PET)
// Sources, in the pixel-pet repo: art/frog_rear.txt, art/seal_rear.txt, art/cat_rear.txt (32x32, "# WxH" header, '.' clear, 1-9 / A palette indices; the pets
// from behind that the Tenis game draws at every stage, with no props) and the palettes PAL_FROG / PAL_SEAL / PAL_CAT and their *_ELDER twins in
// common/sprites.c (RGB565 as the board stores them, expanded the way the city's pets.png was exported). The art_*_back*.txt files are the "Hora de jugar"
// scene's views holding the console, so they are not used.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(process.argv[2] || process.env.PIXEL_PET || join(here, '..', '..', 'pixel-pet'));
const SPECIES = ['frog', 'seal', 'cat'];

const rgb565 = (r, g, b) => { const f = (v, bits) => { const q = v >> (8 - bits); return (q << (8 - bits)) | (q >> (2 * bits - 8)); }; return `#${[f(r, 5), f(g, 6), f(b, 5)].map((v) => v.toString(16).padStart(2, '0')).join('')}`; };

export function parseArt(text) {
  const lines = text.split('\n').filter((l) => l.trim() !== '');
  const m = /^#\s*(\d+)x(\d+)/.exec(lines[0]);
  if (!m) throw new Error('no "# WxH" header');
  const rows = lines.slice(1).map((l) => l.trim());
  if (rows.length !== Number(m[2]) || rows.some((r) => r.length !== Number(m[1]))) throw new Error('art does not match its header');
  return rows;
}

export function parsePalettes(c) {
  const out = {};
  for (const m of c.matchAll(/const gfx_palette_t (PAL_[A-Z_]+) = \{([\s\S]*?)\n\};/g)) {
    out[m[1]] = [...m[2].matchAll(/RGB565\(\s*0x([0-9A-Fa-f]{2}),\s*0x([0-9A-Fa-f]{2}),\s*0x([0-9A-Fa-f]{2})\s*\)/g)].map((x) => rgb565(parseInt(x[1], 16), parseInt(x[2], 16), parseInt(x[3], 16)));
  }
  return out;
}

const KEYS = '123456789ABCDEF';
const paletteOf = (list) => Object.fromEntries(list.map((c, i) => [KEYS[i], c]));      // index 0 is transparent: the list starts at 1 (the literal 0 is not an RGB565 call)

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const pals = parsePalettes(readFileSync(join(repo, 'common', 'sprites.c'), 'utf8'));
  const art = {}, palette = {}, elder = {};
  for (const sp of SPECIES) {
    art[sp] = parseArt(readFileSync(join(repo, 'art', `${sp}_rear.txt`), 'utf8'));
    const base = pals[`PAL_${sp.toUpperCase()}`], old = pals[`PAL_${sp.toUpperCase()}_ELDER`];
    if (!base || !old) throw new Error(`palette of ${sp} not found`);
    palette[sp] = paletteOf(base); elder[sp] = paletteOf(old);
  }
  const lines = [
    '// GENERATED by tools/make-back-sprites.mjs from the board\'s art/<species>_rear.txt and the palettes in common/sprites.c: do not edit by hand.',
    '// The three playable pets seen from behind, 32 x 32, one string per row, the board\'s palette indices (1 outline, 2 shade, 3 body, 4 highlight, 9 stripes /',
    '// glow ... see PALETTE). The same drawing serves every stage (as in the board\'s Tenis game); the elder uses ELDER_PALETTE.',
    `export const PALETTE = ${JSON.stringify(palette)};`,
    `export const ELDER_PALETTE = ${JSON.stringify(elder)};`,
    'export const BACK_ART = {',
  ];
  for (const sp of SPECIES) { lines.push(`  ${sp}: [`); for (const r of art[sp]) lines.push(`    '${r}',`); lines.push('  ],'); }
  lines.push('};', '');
  writeFileSync(join(here, '..', 'src', 'arcade', 'back-art.js'), lines.join('\n'));
  console.log('wrote src/arcade/back-art.js from', repo);
}
